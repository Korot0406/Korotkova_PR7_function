// Задание 3. Напишите шаблонную функцию, которая принимает массив любого числового
// типа и возвращает сумму всех элементов массива.
void problem3(){
    srand(time(0));

    int n = IntEnterNumber("Введите размер массива: ", 1, 1000);
    int* arrInt = new int[n];

    // Массив int
    cout << "Массив типа int: ";
    for(int i = 0; i < n; ++i){
        arrInt[i] = rand() % 20 - 10;
        cout << arrInt[i] << " ";
    }

    int sum_int = sum_array(arrInt, n);
    cout << "\nСумма всех элементова массива типа int: " << sum_int << '\n';

    // Массив double
    double* arrDouble = new double[n];

    cout << "Массив типа double: ";
    for(int i = 0; i < n; ++i){
        arrDouble[i] = (rand() % 200 - 100) / 10.0;
        cout << arrDouble[i] << " ";
    }

    cout << "\nСумма всех элементова массива типа double: " << sum_array(arrDouble, n) << "\n\n";
}

