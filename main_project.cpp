// Задание 5. Напишите функцию, которая находит сумму положительных элементов массива, с использованием лямбда-функции.
void problem5(){
    int n = IntEnterNumber("Введите размер массива: ", 1, 1000);
    int* arr = new int[n];

    // Заполнение массива
    cout << "Исходный массив: ";
    for(int i = 0; i < n; ++i){
        arr[i] = rand() % 20 - 10;
        cout << arr[i] << " ";
    }

    // Лямбда-функция проверки положительного числа
    auto is_positive = [](int  x, int size){
        for(int i = 0; i < size; ++i){
            if(x > 0) return true;
        }
        return false;
    };

    int sum = sum_positive(arr, n, is_positive);
    cout << "\nСумма положительных элементов массива: " << sum << "\n\n";

}


